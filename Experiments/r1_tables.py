"""
r1_tables.py — Revision R1, analysis plan Sections 8 and 10: the PRONOSTIA comparison tables
of the revised manuscript, generated from result files only (no number is typed by hand).

Reads the saved test predictions of both versions of our model and of the seven baselines,
and the strict bearing-level statistics written by r1_strict_stats.py:
  outputs/r1_analysis/strict_temporal_B5.json  (reference: the adopted variant, plan Section 7 B2)
  outputs/r1_analysis/strict_B10.json          (reference: the submitted architecture)
For every bearing set (all10 primary; new6, orig4, zs3 descriptive) it reports
  primary: bearing-averaged CES MAE (seed mean per bearing, then mean over bearings),
           difference to each reference, bearings on which the reference is better,
           exact sign-flip p and Holm-adjusted p (from the strict-statistics files);
  co-reported: window-pooled raw and CES MAE (mean and SD over seeds), raw RMSE and R^2,
           PAVA MAE and R^2 (offline reference).
The comparison of the two versions of our model is descriptive (exact sign-flip test, no family).

USAGE:
  python Experiments/r1_tables.py [--out outputs/r1_analysis/tables_R1.md]
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'Experiments'))
from r1_analysis import load_variant, seed_metrics  # noqa: E402
from r1_provenance import provenance  # noqa: E402
from r1_strict_stats import BASELINES, SETS, baseline_paths, compare, n_preds  # noqa: E402

ADOPTED = ('DSAFLite+PGMC with temporal context (adopted)', 'outputs/r1_final_temporal_B5/final20', 5)
SUBMITTED = ('DSAFLite+PGMC, submitted architecture', 'outputs/r1_final_B10/final20', 10)
STRICT = {'adopted': 'outputs/r1_analysis/strict_temporal_B5.json',
          'submitted': 'outputs/r1_analysis/strict_B10.json'}
MSCNN_SELECTION = 'outputs/r1_mscnn/selection.json'


def budgets():
    """Selected training budget of each baseline, read from its selection file."""
    out = {}
    for label, (short, _) in BASELINES.items():
        f = (ROOT / MSCNN_SELECTION if short == 'mscnn'
             else ROOT / 'outputs' / 'r1_baseline_sel5' / f'{short}.json')
        d = json.loads(f.read_text(encoding='utf-8'))
        out[label] = d['K'] if short == 'mscnn' else d['K_5seed_4fold']
    return out


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=str(ROOT / 'outputs' / 'r1_analysis' / 'tables_R1.md'))
    args = ap.parse_args()

    base_paths = baseline_paths()
    incomplete = [k for k, v in base_paths.items() if n_preds(v) != 20]
    if incomplete:
        raise SystemExit(f'baseline family incomplete: {incomplete}')
    strict = {k: json.loads((ROOT / v).read_text(encoding='utf-8')) for k, v in STRICT.items()}
    for key, (_, path, _) in (('adopted', ADOPTED), ('submitted', SUBMITTED)):
        if strict[key]['reference'] != path or strict[key]['status'] != 'complete':
            raise SystemExit(f'{STRICT[key]} does not hold the complete analysis for {path}')
    k_of = budgets()
    models = {ADOPTED[0]: (ADOPTED[1], ADOPTED[2]), SUBMITTED[0]: (SUBMITTED[1], SUBMITTED[2]),
              **{k: (v, k_of[k]) for k, v in base_paths.items()}}
    data = {k: load_variant(ROOT / v[0]) for k, v in models.items()}

    report = {'models': {k: {'path': v[0], 'budget': v[1]} for k, v in models.items()},
              'strict_files': STRICT, 'sets': {}}
    lines = ['# PRONOSTIA comparison tables (revision R1; generated by Experiments/r1_tables.py)', '',
             'Primary endpoint: bearing-averaged CES MAE. Δ = (comparator − reference) / comparator; '
             'positive: reference better. p: exact two-sided sign-flip test over bearings; Holm: '
             'adjusted over the seven baselines (plan Section 8). Pooled columns: window-pooled metrics, '
             'mean ± SD over 20 seeds. PAVA: offline reference.']
    for set_name in ('all10', 'new6', 'orig4', 'zs3'):
        bearings = SETS[set_name]
        rows = {}
        for name, d in data.items():
            per_seed = [seed_metrics(d[s], bearings, 1.0) for s in sorted(d)]
            pooled = {key: (float(np.mean([r[key] for r in per_seed])), float(np.std([r[key] for r in per_seed])))
                      for key in ('raw_mae', 'ces_mae', 'raw_rmse', 'raw_r2', 'pava_mae', 'pava_r2')}
            b_avg = {m: float(np.mean([np.mean([r['per_bearing'][b][m] for r in per_seed]) for b in bearings]))
                     for m in ('raw', 'ces')}
            rows[name] = {'pooled': pooled, 'bearing_avg': b_avg}
        two = compare(data[ADOPTED[0]], data[SUBMITTED[0]], bearings, 'ces')
        report['sets'][set_name] = {'rows': rows, 'adopted_vs_submitted_ces': {
            k: (list(v) if isinstance(v, tuple) else v) for k, v in two.items()}}
        fam = {key: strict[key]['sets'][set_name]['ces']['baselines'] for key in strict}
        lines += ['', f'## {set_name} ({len(bearings)} bearings; smallest attainable p = '
                      f'{2 / 2 ** len(bearings):.4f})', '',
                  '| Model | B | CES MAE, bearing avg | Δ vs adopted (better on, p, Holm) | '
                  'Δ vs submitted (better on, p, Holm) | raw MAE, bearing avg | pooled raw MAE | '
                  'pooled CES MAE | pooled raw RMSE | pooled raw R² | PAVA MAE (offline) | PAVA R² |',
                  '|---|---|---|---|---|---|---|---|---|---|---|---|']
        for name, r in rows.items():
            cells = []
            for key, ref_name in (('adopted', ADOPTED[0]), ('submitted', SUBMITTED[0])):
                if name == ref_name:
                    cells.append('reference')
                elif name in fam[key]:
                    f = fam[key][name]
                    cells.append(f"{f['rel']:+.1f} % ({f['k']}/{f['n']}, {f['p_flip']:.3f}, {f['p_holm']:.3f})")
                elif key == 'adopted':      # comparator: submitted architecture; reference: adopted
                    cells.append(f"{two['rel']:+.1f} % ({two['k']}/{two['n']}, {two['p_flip']:.3f}, –)")
                else:                       # comparator: adopted; reference: submitted architecture
                    cells.append(f"{100 * (two['ref'] - two['other']) / two['ref']:+.1f} % "
                                 f"({two['n'] - two['k']}/{two['n']}, {two['p_flip']:.3f}, –)")
            p = r['pooled']
            lines.append(
                f"| {name} | {models[name][1]} | {r['bearing_avg']['ces']:.4f} | {cells[0]} | {cells[1]} | "
                f"{r['bearing_avg']['raw']:.4f} | {p['raw_mae'][0]:.4f} ± {p['raw_mae'][1]:.4f} | "
                f"{p['ces_mae'][0]:.4f} ± {p['ces_mae'][1]:.4f} | {p['raw_rmse'][0]:.4f} | "
                f"{p['raw_r2'][0]:.3f} | {p['pava_mae'][0]:.4f} | {p['pava_r2'][0]:.3f} |")
    report['provenance'] = provenance(('Experiments/r1_tables.py', 'Experiments/r1_strict_stats.py',
                                       'Experiments/r1_analysis.py'))
    text = '\n'.join(lines) + '\n'
    print(text)
    Path(args.out).write_text(text, encoding='utf-8')
    Path(args.out).with_suffix('.json').write_text(json.dumps(report, indent=1), encoding='utf-8')
    print(f'written {args.out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
